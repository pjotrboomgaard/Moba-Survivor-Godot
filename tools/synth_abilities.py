# Fallback flavour for archetypes not in ARCHETYPE_FLAVOUR (defensive).
_DEFAULT_FLAVOUR = [dict(wave="chime", f0=1000, f1=700, dur=0.22, amp=0.26, partials=[1.0, 1.5])]


def _seed(ability_id: str) -> int:
    """Deterministic 32-bit seed from the ability id (stable across runs)."""
    return int(hashlib.sha256(ability_id.encode("utf-8")).hexdigest()[:8], 16)


def _pitch_offset(ability_id: str) -> float:
    """Per-ability pitch offset in [0.92, 1.10] so same-hero same-archetype abilities
    never land on an identical pitch. Applied to every layer of the take."""
    norm = (_seed(ability_id) % 1000) / 1000.0
    return 0.92 + 0.18 * norm


def build_ability_take(ability_id: str, archetype: str) -> list:
    hero = ability_id.split("_")[0]
    base_hero = HERO_BASE.get(hero, "astral")
    base_recipes = RECIPES.get(base_hero, RECIPES["astral"])
    # Pick one of the hero's existing base takes (deterministically per ability)
    # so each ability inherits a slightly different element flavour too.
    base_take = base_recipes[_seed("base:" + ability_id) % len(base_recipes)]
    flavour = ARCHETYPE_FLAVOUR.get(archetype, _DEFAULT_FLAVOUR)

    # Clone the base layers and shift them down a touch (the hero base is the
    # "identity" carrier), then append the archetype flavour on top.
    layers = []
    for layer in base_take:
        l = dict(layer)
        l["f0"] = float(l.get("f0", 440)) * 0.85
        l["f1"] = float(l.get("f1", 440)) * 0.85
        l["amp"] = float(l.get("amp", 0.4)) * 0.85
        layers.append(l)
    for fl in flavour:
        fl2 = dict(fl)
        fl2["dur"] = float(fl2.get("dur", 0.2)) * 0.9
        layers.append(fl2)

    # Apply the per-ability pitch offset to all layers.
    po = _pitch_offset(ability_id)
    for l in layers:
        l["f0"] = float(l["f0"]) * po
        l["f1"] = float(l["f1"]) * po
    return layers


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    # Read the ability roster straight from player_class.gd so the generator and
    # the game always agree on the ability set (no hand-maintained list).
    import re
    gd_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts", "player_class.gd")
    s = open(gd_path, encoding="utf-8").read()
    pat = re.compile(
        r'^\t"([a-z_]+)": \{\n\s*"name":\s*".*?",\s*"archetype":\s*Archetype\.([A-Z_]+)',
        re.M,
    )
    abilities = [(m.group(1), m.group(2)) for m in pat.finditer(s)]
    if not abilities:
        print("ERROR: no abilities found in player_class.gd", file=sys.stderr)
        return 1

    written = 0
    for ability_id, archetype in abilities:
        layers = build_ability_take(ability_id, archetype)
        rng = random.Random(_seed("render:" + ability_id))
        pcm = synthesize(layers, rng)
        out_path = os.path.join(OUT_DIR, "ability_" + ability_id + ".wav")
        write_wav(out_path, pcm)
        written += 1
    print("synth_abilities: %d ability wavs written to %s" % (written, OUT_DIR))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
