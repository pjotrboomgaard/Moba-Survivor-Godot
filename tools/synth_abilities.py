"""One-shot generator for per-ABILITY sound banks (T3.8 follow-up: "true 64+").

Every ability in the roster gets its OWN unique procedural SFX so that, within a
single hero, no two abilities sound identical. Each bank is synthesized
procedurally (stdlib only: math/random/wave) -- MIT-safe, no sampled assets --
and is derived from a (hero, archetype) base recipe plus a *deterministic*
per-ability variation (pitch offset, extra partial layer, and a seeded timbre
jitter) so the output is stable across runs while still distinct per ability.

The base recipe is chosen from the hero's element (to match the hero's existing
cast_<hero> / attack_<hero> banks already generated by synth_themes.py) crossed
with the ability's archetype family. The per-ability variation guarantees that,
e.g., tobor_steam_keg and tobor_keg_lob -- both NUKE_BOLT, both tobor -- do NOT
sound the same.

Output: assets/audio/themes/ability_<ability_id>.wav  (one file per ability)

Regenerate everything:
    python tools/synth_abilities.py

The audio_service.gd registers these banks under the id "ability_<ability_id>"
and play_ability() resolves each ability to its own bank, falling back to the
shared cast_<hero> bank, then the archetype family, then a warning.
"""

